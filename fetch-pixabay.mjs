#!/usr/bin/env node
/**
 * Downloads every image/video used by the site from Pixabay (official API)
 * into ./assets and writes ./assets/media.js, which index.html reads.
 *
 * Usage:   PIXABAY_KEY=your_key node fetch-pixabay.mjs
 * Get a free key at https://pixabay.com/api/docs/ (log in, key is shown there).
 *
 * Pixabay's API terms ask that media be downloaded to your own server rather
 * than hotlinked — that's what this script does. Re-run any time; change a
 * slot's `q` (search words) or `pick` (which result, 0 = first) to swap media.
 */
import { writeFile, mkdir } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const KEY = process.env.PIXABAY_KEY;
if (!KEY) { console.error('Set PIXABAY_KEY first:  PIXABAY_KEY=xxxx node fetch-pixabay.mjs'); process.exit(1); }
const ROOT = dirname(fileURLToPath(import.meta.url));

// slot name -> search. type: 'image' | 'video'
const SLOTS = {
  hero:            { type: 'video', q: 'plastic production' },
  about:           { type: 'image', q: 'factory machine industry' },
  prodPreforms:    { type: 'image', q: 'bottling', pick: 5 },
  prodClosures:    { type: 'image', q: 'plastic bottle caps' },
  prodContainers:  { type: 'image', q: 'plastic bottles production' },
  prodFlexible:    { type: 'image', q: 'food packaging' },
  techInjection:   { type: 'image', q: 'plastic granules' },
  techCompression: { type: 'image', q: 'plastic caps colorful' },
  techISBM:        { type: 'image', q: 'empty plastic bottles' },
  indWater:        { type: 'image', q: 'mineral water bottle' },
  indOil:          { type: 'image', q: 'cooking oil bottle' },
  indPharma:       { type: 'image', q: 'medicine bottle' },
  indDairy:        { type: 'image', q: 'milk bottle' },
  indCare:         { type: 'image', q: 'shampoo bottle' },
  indFmcg:         { type: 'image', q: 'supermarket shelf' },
  ctaVideo:        { type: 'video', q: 'bottle factory', pick: 1 },
};

const api = (type, q) => {
  const base = type === 'video' ? 'https://pixabay.com/api/videos/' : 'https://pixabay.com/api/';
  const p = new URLSearchParams({ key: KEY, q, safesearch: 'true', per_page: '10', order: 'popular' });
  if (type === 'image') { p.set('image_type', 'photo'); p.set('orientation', 'horizontal'); p.set('min_width', '1280'); }
  return `${base}?${p}`;
};

async function download(url, file) {
  const r = await fetch(url);
  if (!r.ok) throw new Error(`${r.status} for ${url}`);
  await mkdir(dirname(file), { recursive: true });
  await writeFile(file, Buffer.from(await r.arrayBuffer()));
}

const media = {};
for (const [slot, cfg] of Object.entries(SLOTS)) {
  try {
    const res = await fetch(api(cfg.type, cfg.q));
    if (!res.ok) throw new Error(`API ${res.status}: ${await res.text()}`);
    const { hits } = await res.json();
    const hit = hits?.[cfg.pick ?? 0];
    if (!hit) { console.warn(`! ${slot}: no results for "${cfg.q}"`); continue; }
    if (cfg.type === 'video') {
      const v = hit.videos.medium?.url ? hit.videos.medium : hit.videos.small;
      const src = `assets/video/${slot}.mp4`, poster = `assets/img/${slot}-poster.jpg`;
      await download(v.url, join(ROOT, src));
      if (v.thumbnail) await download(v.thumbnail, join(ROOT, poster));
      media[slot] = { type: 'video', src, poster: v.thumbnail ? poster : '', by: hit.user, page: hit.pageURL };
    } else {
      const src = `assets/img/${slot}.jpg`;
      await download(hit.largeImageURL, join(ROOT, src));
      media[slot] = { type: 'image', src, by: hit.user, page: hit.pageURL, alt: hit.tags };
    }
    console.log(`✓ ${slot.padEnd(16)} ${cfg.type}  by ${hit.user}`);
  } catch (e) { console.warn(`! ${slot}: ${e.message}`); }
}

await writeFile(join(ROOT, 'assets/media.js'),
  `// Generated by fetch-pixabay.mjs — media from Pixabay (pixabay.com)\nwindow.MEDIA = ${JSON.stringify(media, null, 2)};\n`);
console.log(`\nWrote assets/media.js with ${Object.keys(media).length}/${Object.keys(SLOTS).length} slots.`);
